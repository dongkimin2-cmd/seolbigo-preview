// 카테고리 이모지 → 아이콘 선 색 (파스텔 배경 위)
export const EMOJI_FG: Record<string, string> = {
  '💧': '#E5484D', '🔧': '#693BF2', '🔍': '#0087FF', '🌀': '#FF7C11',
  '🧱': '#00A163', '🚿': '#0E7490', '♨': '#E8A200', '🛸': '#4263EB',
};

function lookup(e: string): string | undefined {
  return EMOJI_ICON[e.replace('️', '')] ?? EMOJI_ICON[e];
}

// 단일 이모지(카테고리 아이콘 등) → 아이콘. 카테고리색이 있으면 색 래퍼 포함. 매핑 없으면 원문 유지
export function emojiIcon(e: string): ReactNode {
  const id = lookup(e);
  if (!id) return e;
  const fg = EMOJI_FG[e.replace('️', '')];
  return fg
    ? <span style={{ color: fg, display: 'contents' }}><Ic id={id} /></span>
    : <Ic id={id} />;
}

// '📥 요청 인박스' 같은 라벨 → 아이콘 + 텍스트. 매핑 없으면 원문 유지
export function labelWithIcon(label: string): ReactNode {
  const first = Array.from(label)[0] ?? '';
  const id = lookup(first);
  if (!id) return label;
  return <><Ic id={id} /> {label.slice(first.length).replace(/^️?\s*/, '')}</>;
}

// 문자열 안의 매핑된 이모지를 전부 아이콘으로 치환 ('📷📐 사진과 면적…' 같은 복수 이모지 지원)
export function iconizeText(text: string): ReactNode {
  const out: ReactNode[] = [];
  let buf = '';
  let k = 0;
  for (const ch of Array.from(text)) {
    if (ch === '️') continue; // variation selector
    const id = EMOJI_ICON[ch];
    if (id) {
      if (buf) { out.push(buf); buf = ''; }
      out.push(<Ic key={k++} id={id} />);
    } else {
      buf += ch;
    }
  }
  if (buf) out.push(buf);
  return <>{out}</>;
}
